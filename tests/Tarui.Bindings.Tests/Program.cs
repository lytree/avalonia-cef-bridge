using System.Text;
using System.Text.RegularExpressions;
using Tarui.Contracts;

namespace Tarui.Bindings.Tests;

/// <summary>
/// Drift gate for the typed command contract. It unions the per-assembly
/// <c>{Assembly}CommandCatalog.Contracts</c> emitted by Tarui.Ipc.Generators, cross-checks it against
/// the hand-written <c>@lytree/api</c> bindings, and keeps the generated TypeScript declaration
/// (<c>web/packages/api/generated/commands.ts</c>) in step with it.
/// </summary>
internal static class Program
{
    private static readonly Regex InvokeLiteralPattern = new(
        @"\binvoke\s*(?:<[^>]*>)?\s*\(\s*'([^']+)'",
        RegexOptions.Compiled | RegexOptions.CultureInvariant);

    /// <summary>
    /// Commands the shell posts on its own (never written as an <c>invoke('…')</c> literal in
    /// <c>@lytree/api</c>), so the front-end scan legitimately never finds them.
    /// </summary>
    private static readonly string[] InternalOnlyCommands =
    [
        "plugin:webview|eval-callback-complete",
    ];

    public static int Main(string[] args)
    {
        var generated = CollectGeneratedContracts();
        var types = CollectGeneratedTypes();
        var update = args.Contains("--update", StringComparer.Ordinal);

        Assert(generated.Count > 0, "The generated command contract must not be empty.");
        Assert(types.Count > 0, "The generated type contract must not be empty.");
        FrontendInvokeLiteralsMatchGeneratedCommandContract(generated);
        InternalOnlyCommandsAreAllowlisted(generated);
        GeneratedCommandContractCarriesUniqueTypedEntries(generated);
        GeneratedTypeShapesResolveEveryPayload(generated, types);
        TypeScriptDeclarationMatchesGeneratedContract(generated, types, update);

        Console.WriteLine("Tarui.Bindings self-tests passed.");
        return 0;
    }

    /// <summary>
    /// Regenerates (with <c>--update</c>) or verifies the checked-in TypeScript declaration. The
    /// declaration is the front-end's compile-time view of the command surface: a command id, its
    /// gating permission and its DTO names, so a missing or renamed command breaks at type-check time
    /// instead of at runtime. The file is a type-only module, re-exported by the package barrel.
    /// </summary>
    private static void TypeScriptDeclarationMatchesGeneratedContract(
        IReadOnlyList<TaruiCommandContract> generated,
        IReadOnlyList<TaruiTypeContract> types,
        bool update)
    {
        var path = Path.Combine(
            RepositoryRoot.Find(), "web", "packages", "api", "generated", "commands.ts");
        var expected = BuildTypeScriptDeclaration(generated, types);

        if (update)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, expected, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            Console.WriteLine($"Updated {path}");
            return;
        }

        Assert(
            File.Exists(path),
            $"The generated TypeScript command declaration is missing at '{path}'. "
                + "Run `dotnet run --project tests/Tarui.Bindings.Tests -- --update`.");

        var actual = File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal);
        Assert(
            string.Equals(actual, expected, StringComparison.Ordinal),
            $"The TypeScript command declaration at '{path}' is stale. "
                + "Run `dotnet run --project tests/Tarui.Bindings.Tests -- --update` and commit the result.");
    }

    private static string BuildTypeScriptDeclaration(
        IReadOnlyList<TaruiCommandContract> contracts,
        IReadOnlyList<TaruiTypeContract> types)
    {
        var orderedTypes = types
            .GroupBy(static type => type.Name, StringComparer.Ordinal)
            .Select(static group => group.First())
            .OrderBy(static type => type.Name, StringComparer.Ordinal)
            .ToArray();
        var expressions = orderedTypes.ToDictionary(
            static type => type.Name,
            static type => type.TypeExpression,
            StringComparer.Ordinal);
        var orderedContracts = contracts.OrderBy(static c => c.Id, StringComparer.Ordinal).ToArray();

        var builder = new StringBuilder();
        builder.Append("// <auto-generated />\n");
        builder.Append("// Generated from the Tarui.Ipc.Generators command catalogs; do not edit by hand.\n");
        builder.Append("// Regenerate with: dotnet run --project tests/Tarui.Bindings.Tests -- --update\n");
        builder.Append('\n');
        builder.Append("// ---------------------------------------------------------------------------\n");
        builder.Append("// Payload types\n");
        builder.Append("// ---------------------------------------------------------------------------\n");
        builder.Append('\n');
        builder.Append("/**\n");
        builder.Append(" * Argument and result shapes, resolved from the JSON DTOs behind `TaruiJsonContext`\n");
        builder.Append(" * (camelCase members, null members omitted). A DTO field rename therefore breaks the\n");
        builder.Append(" * front-end at type-check time instead of at runtime.\n");
        builder.Append(" */\n");

        foreach (var type in orderedTypes)
        {
            // Only object DTOs declare a type; scalars, arrays and dictionaries appear as expressions
            // on the command side (e.g. the `FsDirEntryArray` member is `FsDirEntry[]`).
            if (!string.Equals(type.TypeExpression, type.Name, StringComparison.Ordinal))
            {
                continue;
            }

            if (type.Body.Length == 0)
            {
                builder.Append("export type ").Append(type.Name).Append(" = Record<string, never>;\n\n");
                continue;
            }

            builder.Append("export interface ").Append(type.Name).Append(" {\n");
            foreach (var line in type.Body.Split('\n'))
            {
                if (line.Length > 0)
                {
                    builder.Append("  ").Append(line).Append('\n');
                }
            }

            builder.Append("}\n\n");
        }

        builder.Append("// ---------------------------------------------------------------------------\n");
        builder.Append("// Command surface\n");
        builder.Append("// ---------------------------------------------------------------------------\n");
        builder.Append('\n');
        builder.Append("/**\n");
        builder.Append(" * Every routed command: the permission that gates it and the catalog names of its\n");
        builder.Append(" * argument and result. The JSON shape is owned by those DTOs (TaruiJsonContext).\n");
        builder.Append(" */\n");
        builder.Append("export interface TaruiCommandContracts {\n");

        foreach (var contract in orderedContracts)
        {
            builder.Append("  readonly \"").Append(EscapeTypeScript(contract.Id)).Append("\": {\n");
            builder.Append("    readonly permission: \"").Append(EscapeTypeScript(contract.Permission)).Append("\";\n");
            builder.Append("    readonly input: \"").Append(EscapeTypeScript(contract.Input)).Append("\";\n");
            builder.Append("    readonly output: \"").Append(EscapeTypeScript(contract.Output)).Append("\";\n");
            builder.Append("  };\n");
        }

        builder.Append("}\n");
        builder.Append('\n');
        builder.Append("/** The argument and result type of every command, keyed by command id. */\n");
        builder.Append("export interface TaruiCommandTypes {\n");

        foreach (var contract in orderedContracts)
        {
            builder.Append("  readonly \"").Append(EscapeTypeScript(contract.Id)).Append("\": {\n");
            builder.Append("    readonly input: ").Append(ExpressionOf(expressions, contract.Input)).Append(";\n");
            builder.Append("    readonly output: ").Append(ExpressionOf(expressions, contract.Output)).Append(";\n");
            builder.Append("  };\n");
        }

        builder.Append("}\n");
        builder.Append('\n');
        builder.Append("/** The union of every command id the native side registers. */\n");
        builder.Append("export type TaruiCommandId = keyof TaruiCommandContracts;\n");
        builder.Append('\n');
        builder.Append("/** The argument type of a command. */\n");
        builder.Append("export type TaruiCommandInput<TCommand extends TaruiCommandId> =\n");
        builder.Append("  TaruiCommandTypes[TCommand]['input'];\n");
        builder.Append('\n');
        builder.Append("/** The result type of a command. */\n");
        builder.Append("export type TaruiCommandResult<TCommand extends TaruiCommandId> =\n");
        builder.Append("  TaruiCommandTypes[TCommand]['output'];\n");
        return builder.ToString();
    }

    private static string ExpressionOf(Dictionary<string, string> expressions, string name) =>
        expressions.TryGetValue(name, out var expression) ? expression : "unknown";

    private static string EscapeTypeScript(string value) => value
        .Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal);

    private static void FrontendInvokeLiteralsMatchGeneratedCommandContract(
        IReadOnlyList<TaruiCommandContract> generated)
    {
        var known = generated.Select(static contract => contract.Id).ToHashSet(StringComparer.Ordinal);
        var invoked = ReadFrontendInvokeLiterals();

        Assert(invoked.Count > 0, "The front-end scan must find at least one invoke() literal.");

        var unknown = invoked
            .Where(id => !known.Contains(id))
            .OrderBy(static id => id, StringComparer.Ordinal)
            .ToArray();
        Assert(
            unknown.Length == 0,
            "Every command the front end invokes must exist in the generated contract; unknown: "
                + string.Join(", ", unknown));

        var allowlist = InternalOnlyCommands.ToHashSet(StringComparer.Ordinal);
        var unbound = known
            .Where(id => !invoked.Contains(id) && !allowlist.Contains(id))
            .OrderBy(static id => id, StringComparer.Ordinal)
            .ToArray();
        Assert(
            unbound.Length == 0,
            "Every generated command must be invoked by the front end or allowlisted as internal-only; unbound: "
                + string.Join(", ", unbound));
    }

    private static void InternalOnlyCommandsAreAllowlisted(IReadOnlyList<TaruiCommandContract> generated)
    {
        var known = generated.Select(static contract => contract.Id).ToHashSet(StringComparer.Ordinal);
        foreach (var command in InternalOnlyCommands)
        {
            Assert(
                known.Contains(command),
                $"Allowlisted internal command '{command}' must exist in the generated contract.");
        }
    }

    private static void GeneratedCommandContractCarriesUniqueTypedEntries(
        IReadOnlyList<TaruiCommandContract> generated)
    {
        foreach (var contract in generated)
        {
            Assert(!string.IsNullOrWhiteSpace(contract.Id), "A generated command contract must carry an id.");
            Assert(!string.IsNullOrWhiteSpace(contract.Input), $"Command '{contract.Id}' must declare an input DTO.");
            Assert(!string.IsNullOrWhiteSpace(contract.Output), $"Command '{contract.Id}' must declare an output DTO.");
            Assert(
                !string.IsNullOrWhiteSpace(contract.Permission),
                $"Command '{contract.Id}' must declare the permission that gates it.");
        }

        var duplicates = generated
            .GroupBy(static contract => contract.Id, StringComparer.Ordinal)
            .Where(static group => group.Count() > 1)
            .Select(static group => group.Key)
            .OrderBy(static id => id, StringComparer.Ordinal)
            .ToArray();
        Assert(
            duplicates.Length == 0,
            "Generated command ids must be unique; duplicates: " + string.Join(", ", duplicates));
    }

