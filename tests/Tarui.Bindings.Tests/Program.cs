    /// <summary>
    /// Every command must resolve to a payload shape, and one catalog name may not describe two
    /// different types. Both failures would silently degrade the generated declaration to `unknown`,
    /// which is exactly the drift this gate exists to catch.
    /// </summary>
    private static void GeneratedTypeShapesResolveEveryPayload(
        IReadOnlyList<TaruiCommandContract> generated,
        IReadOnlyList<TaruiTypeContract> types)
    {
        foreach (var contract in generated)
        {
            Assert(
                !string.IsNullOrWhiteSpace(contract.Input),
                $"Command '{contract.Id}' must declare an input payload.");
            Assert(
                !string.IsNullOrWhiteSpace(contract.Output),
                $"Command '{contract.Id}' must declare an output payload.");
        }

        var conflicts = types
            .GroupBy(static type => type.Name, StringComparer.Ordinal)
            .Where(static group => group
                .Select(type => type.TypeExpression + "\u0000" + type.Body)
                .Distinct(StringComparer.Ordinal)
                .Count() > 1)
            .Select(static group => group.Key)
            .OrderBy(static name => name, StringComparer.Ordinal)
            .ToArray();
        Assert(
            conflicts.Length == 0,
            "One catalog name must describe exactly one type; conflicting names: "
                + string.Join(", ", conflicts));

        var known = types.Select(static type => type.Name).ToHashSet(StringComparer.Ordinal);
        var unresolved = generated
            .SelectMany(static contract => new[]
            {
                (contract.Id, Name: contract.Input),
                (contract.Id, Name: contract.Output),
            })
            .Where(entry => !known.Contains(entry.Name))
            .Select(static entry => $"{entry.Id} -> {entry.Name}")
            .OrderBy(static entry => entry, StringComparer.Ordinal)
            .ToArray();
        Assert(
            unresolved.Length == 0,
            "Every command payload must resolve to a generated type shape; unresolved: "
                + string.Join(", ", unresolved));

        Assert(
            !types.Any(static type => type.TypeExpression.Length == 0),
            "Type expressions must never be empty.");
        Assert(
            types.Any(static type => type.Body.Length > 0),
            "At least one object DTO must expose its members, otherwise the shape reader resolved nothing.");

        foreach (var type in types.Where(static type => type.Body.Length > 0))
        {
            foreach (var member in type.Body.Split('\n'))
            {
                Assert(
                    member.EndsWith(';'),
                    $"Every member of '{type.Name}' must be a terminated TypeScript property; got '{member}'.");
            }
        }
    }

